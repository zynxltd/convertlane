<h2>Termination, suspensions, and remediation</h2>

<p>Networks reserve the right to suspend or terminate accounts that breach the <a href="{{ route('affiliate-agreement') }}">Affiliate Agreement</a>, IO terms, or applicable law. Suspension may be immediate where consumer harm, fraud, or regulatory risk is suspected. Publishers should understand clawback provisions: commissions on non-compliant or unvalidated conversions can be reversed.</p>

<p>Remediation paths exist for good-faith operators who self-report issues early. Document your corrective actions, removed creatives, updated consent banners, negative keyword refreshes, and cooperate with investigations. Repeat violations, evasion using new accounts, or failure to respond to compliance notices typically lead to permanent removal from the network.</p>

<h3>Termination risk checklist</h3>

<ul>
    <li>Respond to compliance emails within the stated deadline, silence is treated as non-cooperation.</li>
    <li>Pause affected campaigns immediately when notified of a potential breach.</li>
    <li>Preserve relevant logs and creatives until a matter is formally closed.</li>
    <li>Do not attempt to reapply under a new entity after termination for cause.</li>
    <li>Understand how pending commissions are handled during investigations.</li>
</ul>

<h2>Audit logs and ongoing documentation</h2>

<p>Regulators and network compliance teams ask a simple question: “Show us what ran, when, and under which approvals.” Audit logs answer that question. Maintain a central repository of IO PDFs, approved creative versions, disclosure screenshots, consent configuration exports, keyword lists, and change histories for landing pages.</p>

<p>Schedule quarterly self-audits even when campaigns appear stable. Offer terms change, platform policies update, and junior team members may deploy unapproved variants. An hour of proactive review prevents weeks of dispute resolution.</p>

<h3>Audit log checklist</h3>

<ul>
    <li>Store IOs and amendments with effective dates and responsible signatories.</li>
    <li>Version-control landing page HTML or maintain CMS revision history exports.</li>
    <li>Log who published or edited each creative asset and which sub-ID it maps to.</li>
    <li>Archive weekly search term reports where brand bidding restrictions apply.</li>
    <li>Keep CMP consent statistics and privacy policy change records for at least the statutory retention period.</li>
    <li>Summarise findings from each internal audit in a dated memo stored with your compliance file.</li>
</ul>

<h2>Master compliance checklist for 2026</h2>

<p>Before you increase budgets or onboard new sub-affiliates, walk through this consolidated list:</p>

<ul>
    <li>IO terms read and stored; restrictions on geo, channel, brand bidding, and incentives understood.</li>
    <li>Privacy notice and consent mechanisms compliant with UK GDPR; data processing agreements in place.</li>
    <li>ASA/FTC-style disclosures clear, prominent, and platform-appropriate on every commercial touchpoint.</li>
    <li>Pre-landers and landers approved, transparent, and free of misleading urgency or impersonation.</li>
    <li>Claims substantiated; pricing and representative costs accurate and current.</li>
    <li>Tracking honest and technically correct; fraud monitoring active on new sources.</li>
    <li>Audit logs complete enough to reconstruct campaigns months later.</li>
    <li>Escalation path defined: who on your team contacts ConvertLane compliance and when.</li>
</ul>

<p>Operators who internalise these habits spend less time firefighting account warnings and more time scaling durable revenue. Compliance is not a blocker to performance, it is the foundation that keeps performance marketable to tier-one advertisers.</p>

<h2>Frequently asked questions</h2>

<h3>Does GDPR apply if my business is outside the EU and UK?</h3>
<p>Yes, if you process personal data of individuals located in the UK or EEA,  for example, through UK-targeted campaigns or EU-hosted landing pages. Territorial scope follows the data subjects, not only your company registration. Review transfer mechanisms if data flows to countries without adequacy decisions.</p>

<h3>Is “#affiliate” an acceptable disclosure under ASA rules?</h3>
<p>Probably not on its own. The ASA expects labels that the average consumer understands. “Ad”, “Advertisement”, or explicit wording about commission earnings is safer. Context matters: a long-form review article needs clearer labelling than a short social post where “#ad” may suffice if prominently placed.</p>

<h3>Can I bid on a brand name if I am an authorised reseller?</h3>
<p>Only if the IO explicitly permits it. Authorised reseller status with the advertiser does not automatically override network brand-bidding restrictions. Obtain written confirmation in the IO or a compliance addendum before launching search ads.</p>

<h3>What should I do if I discover a sub-affiliate violating policy?</h3>
<p>Pause their traffic immediately, preserve evidence, and notify ConvertLane compliance. Continuing to earn from known violations exposes you to clawbacks and termination. Your agreement typically requires you to police downstream partners.</p>

<h3>How long should I keep compliance records?</h3>
<p>Retain records for at least as long as the limitation period for relevant claims in your jurisdiction, and in line with data minimisation under GDPR. Many operators keep campaign audit files for a minimum of two years; finance and health verticals often require longer retention.</p>

